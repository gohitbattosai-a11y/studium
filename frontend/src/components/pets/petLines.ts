export const greeting = (hour: number, nick: string): string => {
  if (hour < 6) return `${nick}, è tardi! Un po' di riposo?`;
  if (hour < 12) return `Buongiorno ${nick}!`;
  if (hour < 18) return `Buon pomeriggio ${nick}!`;
  return `Buonasera ${nick}!`;
};
